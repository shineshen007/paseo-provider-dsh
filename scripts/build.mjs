#!/usr/bin/env node
/**
 * Build both halves of paseo-provider-dsh.
 *
 * Two constraints drive this script:
 *
 * 1. The Paseo plugin is loaded by the Paseo daemon from the plugin directory.
 *    Bundling it into one file with everything except the host-provided SDK
 *    inlined removes any dependency on the daemon's module resolution, so the
 *    plugin works identically from a directory install, an npm install, or a
 *    Git install.
 * 2. The DSH bridge is loaded by a `dsh` host from a profile's node_modules.
 *    It must stay a small ESM file with no imports beyond Node built-ins,
 *    because the profile owns that dependency tree.
 */

import { build } from "esbuild";
import { chmodSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");

/** Package versions used in the bridge handshake and the build manifest. */
const pkg = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
const bridgePkg = JSON.parse(readFileSync(join(root, "dsh-bridge", "package.json"), "utf8"));

/** Shared esbuild settings. */
const common = {
  platform: "node",
  target: "node20",
  format: "esm",
  bundle: true,
  sourcemap: true,
  logLevel: "warning",
};

/**
 * Fail the build when the two copies of the wire contract drift.
 *
 * `shared/wire.ts` is the copy Paseo compiles into the plugin bundles;
 * `dsh-bridge/src/wire.ts` is the copy the separately installed DSH package
 * carries. They must stay byte-identical, because a mismatch would be a silently
 * different protocol on each end.
 */
function assertWireCopiesMatch() {
  const a = readFileSync(join(root, "shared", "wire.ts"), "utf8");
  const b = readFileSync(join(root, "dsh-bridge", "src", "wire.ts"), "utf8");
  if (a !== b) {
    throw new Error(
      "shared/wire.ts and dsh-bridge/src/wire.ts have drifted; copy one over the other before building",
    );
  }
}

async function main() {
  assertWireCopiesMatch();
  // ---- Paseo plugin server half -------------------------------------------
  // Loaded by the Paseo daemon. Only the Paseo SDK stays external; everything
  // else is inlined so the daemon never resolves our dependencies.
  await build({
    ...common,
    entryPoints: [join(root, "index.server.ts")],
    outfile: join(root, "dist", "index.server.js"),
    external: ["@getpaseo/plugin", "@getpaseo/protocol", "zod"],
  });

  // ---- Test bundle --------------------------------------------------------
  // The e2e harness imports the provider as plain ESM from dist/. Bundling it
  // separately keeps the test independent of the daemon's TypeScript loading.
  await build({
    ...common,
    entryPoints: [join(root, "server", "provider.ts")],
    outfile: join(root, "dist", "bundle", "provider.mjs"),
    external: ["@getpaseo/plugin", "@getpaseo/protocol", "zod"],
  });

  // ---- DSH bridge ----------------------------------------------------------
  // Loaded by a dsh profile host: Node built-ins and the host's own
  // `@deepseek-ai/cordis` only, so every other DSH service arrives through the
  // plugin context instead of a second copy of DSH types.
  await build({
    ...common,
    entryPoints: [join(root, "dsh-bridge", "src", "index.ts")],
    outfile: join(root, "dsh-bridge", "lib", "index.js"),
    external: ["node:*", "@deepseek-ai/cordis"],
    define: { __BRIDGE_VERSION__: JSON.stringify(bridgePkg.version) },
    banner: {
      js: `// dsh-paseo-bridge ${bridgePkg.version} — generated by scripts/build.mjs, do not edit.`,
    },
  });

  // Fail loudly if the injected version never reached the bundle: `doctor` and
  // the handshake must report the built version, not a stale literal.
  const bridgeEntry = join(root, "dsh-bridge", "lib", "index.js");
  const built = readFileSync(bridgeEntry, "utf8");
  if (!built.includes(`"${bridgePkg.version}"`)) {
    throw new Error(`bridge bundle does not carry version ${bridgePkg.version}`);
  }

  // The build manifest lets `doctor` and the installer verify what is deployed
  // without parsing bundles.
  mkdirSync(join(root, "dist"), { recursive: true });
  writeFileSync(
    join(root, "dist", "build.json"),
    `${JSON.stringify(
      {
        plugin: pkg.name,
        version: pkg.version,
        bridgeVersion: bridgePkg.version,
        entry: "dist/index.server.js",
        bridgeEntry: "dsh-bridge/lib/index.js",
      },
      null,
      2,
    )}\n`,
  );

  for (const script of ["install.sh", "uninstall.sh", "rollback.sh"]) {
    try {
      chmodSync(join(root, "scripts", script), 0o755);
    } catch {
      // Optional during incremental development.
    }
  }

  process.stdout.write(`built ${pkg.name}@${pkg.version} and dsh-paseo-bridge@${bridgePkg.version}\n`);
}

await main();
